export const SALES_TYPE_META = Object.fromEntries(
  SALES_APPOINTMENT_TYPES.map((t) => [t.key, t])
);

/** สีพื้น/สีตัวอักษรของนัดหมาย — ใช้ทั้งตอนบันทึกและตอนวาดบนปฏิทิน */
export const salesEventColors = (type) => {
  const meta = SALES_TYPE_META[type] || SALES_TYPE_META["อื่นๆ"];
  return { backgroundColor: meta.color, textColor: "#ffffff" };
};

/**
 * สถานะของนัดหมายฝ่ายขาย
 *
 * ⚠️ **คนละชุดกับสถานะงานช่างโดยตั้งใจ** — ของช่างคือ กำลังรอยืนยัน → ยืนยันแล้ว → กำลังดำเนินการ →
 * ดำเนินการเสร็จสิ้น ซึ่งผูกกับการอนุมัติ/เข้าหน้างาน/ปิดงานพร้อมเอกสาร นัดของเซลไม่มีขั้นตอนพวกนั้นเลย
 * มีแค่ "นัดไว้ / ไปมาแล้ว / เลื่อน / ยกเลิก"
 *
 * 🐛 ที่แก้: เดิมนัดของเซลถูกบันทึกด้วยสถานะ "กำลังรอยืนยัน" ของช่างตายตัวและไม่มีที่ให้แก้เลย
 * นัดที่ไปมาแล้วเมื่อเดือนก่อนก็ยังขึ้นว่า "กำลังรอยืนยัน" อยู่ — ตัวเลขบนหน้าสรุปจึงไม่มีความหมาย
 */
export const SALES_STATUSES = [
  { key: "นัดหมายแล้ว", color: "#8b5cf6", icon: "📌", hint: "ยังไม่ถึงวันนัด" },
  { key: "เข้าพบแล้ว",  color: "#10b981", icon: "✅", hint: "ไปมาแล้ว เรียบร้อย" },
  { key: "เลื่อนนัด",   color: "#f59e0b", icon: "🕘", hint: "ลูกค้าขอเลื่อน" },
  { key: "ยกเลิกนัด",   color: "#94a3b8", icon: "✖️", hint: "ไม่ได้ไปแล้ว" },
];

export const SALES_STATUS_DEFAULT = SALES_STATUSES[0].key;

const SALES_STATUS_META = Object.fromEntries(SALES_STATUSES.map((s) => [s.key, s]));

/**
 * ⚠️ นัดที่สร้างไว้ก่อนมีชุดสถานะนี้ถือสถานะของช่างติดมา (ส่วนใหญ่คือ "กำลังรอยืนยัน") — ต้องแปลง
 * ให้อ่านรู้เรื่อง ไม่ใช่ปล่อยให้หน้าจอพังหรือโชว์คำของอีกแผนก และไม่ต้องไปไล่แก้ข้อมูลเก่าในฐานข้อมูล
 */
const LEGACY_MAP = {
  "กำลังรอยืนยัน": "นัดหมายแล้ว",
  "ยืนยันแล้ว": "นัดหมายแล้ว",
  "กำลังดำเนินการ": "นัดหมายแล้ว",
  "ดำเนินการเสร็จสิ้น": "เข้าพบแล้ว",
};

/** แปลงค่าที่เก็บอยู่ให้เป็นสถานะนัดหมายเสมอ — ใช้ทั้งตอนแสดงผลและตอนตั้งค่าเริ่มต้นในฟอร์มแก้ไข */
export const toSalesStatus = (raw) => {
  const s = String(raw || "").trim();
  if (SALES_STATUS_META[s]) return s;
  return LEGACY_MAP[s] || SALES_STATUS_DEFAULT;
};

/** meta ของสถานะ (สี/ไอคอน) — รับค่าดิบได้เลย ไม่ต้องแปลงมาก่อน */
export const salesStatusMeta = (raw) => SALES_STATUS_META[toSalesStatus(raw)];
