/**
 * ✅ (7 ต.ค. 2569) ผู้ใช้: "เซลเข้างานแล้ว จะกดเข้าพบแล้ว และปิดงาน ต้องให้อัพรูปหน้างานก่อน"
 *    "เข้าพบแล้ว"/"ปิดงานแล้ว" เปลี่ยนได้จากหน้ารายละเอียดนัด (SalesAppointmentDialog) เท่านั้น — ต้องมีรูปหน้างาน
 *    ฟอร์มเพิ่ม/แก้ไขเลือกได้แค่สถานะที่ manual:true · server ตรวจซ้ำอีกชั้น (PUT /events/:id/sales-status)
 */
export const SALES_MANUAL_STATUSES = SALES_STATUSES.filter((s) => s.manual);
export const SALES_PHOTO_REQUIRED = ["เข้าพบแล้ว", "ปิดงานแล้ว"];

export const SALES_STATUS_DEFAULT = SALES_STATUSES[0].key;

const SALES_STATUS_META = Object.fromEntries(SALES_STATUSES.map((s) => [s.key, s]));

/**
 * ⚠️ นัดที่สร้างไว้ก่อนมีชุดสถานะนี้ถือสถานะของช่างติดมา (ส่วนใหญ่คือ "กำลังรอยืนยัน") — ต้องแปลง
 * ให้อ่านรู้เรื่อง ไม่ใช่ปล่อยให้หน้าจอพังหรือโชว์คำของอีกแผนก และไม่ต้องไปไล่แก้ข้อมูลเก่าในฐานข้อมูล
 */
const LEGACY_MAP = {
  "กำลังรอยืนยัน": "นัดหมายแล้ว",
  "ยืนยันแล้ว": "นัดหมายแล้ว",
  "กำลังดำเนินการ": "นัดหมายแล้ว",
  "ดำเนินการเสร็จสิ้น": "ปิดงานแล้ว",
};

/** แปลงค่าที่เก็บอยู่ให้เป็นสถานะนัดหมายเสมอ — ใช้ทั้งตอนแสดงผลและตอนตั้งค่าเริ่มต้นในฟอร์มแก้ไข */
export const toSalesStatus = (raw) => {
  const s = String(raw || "").trim();
  if (SALES_STATUS_META[s]) return s;
  return LEGACY_MAP[s] || SALES_STATUS_DEFAULT;
};

/** meta ของสถานะ (สี/ไอคอน) — รับค่าดิบได้เลย ไม่ต้องแปลงมาก่อน */
export const salesStatusMeta = (raw) => SALES_STATUS_META[toSalesStatus(raw)];
