/**
 * timeFormat — เวลาแบบ "ชม:นาที" มาตรฐานเดียวกันทั้งฟอร์มลงงาน/แก้ไขงาน
 *
 * 🐛 (28 พ.ย. 2569 ผู้ใช้: "ตรวจสอบข้อมูลที่ไม่สอดคล้อง และแสดงผิดพลาด ให้สมบูรณ์")
 *    ช่องเวลาเป็นช่องพิมพ์อิสระ — งานเก่าบางงานเก็บ "18.00" / "8.30" ขณะที่การ์ด/เอกสารอื่นใช้ "08:30"
 *    → แสดงและบันทึกเป็นแบบเดียวกัน: "18.00" → "18:00" · "8.30 น." → "08:30" · ค่าที่อ่านไม่ออกคงเดิม (ไม่เดา)
 */
export const normTime = (raw) => {
  const t = String(raw ?? "").trim();
  const m = t.match(/^(\d{1,2})[.:](\d{2})(?:\s*น\.?)?$/);
  if (!m || Number(m[1]) > 24 || Number(m[2]) > 59) return t;
  return `${m[1].padStart(2, "0")}:${m[2]}`;
};
